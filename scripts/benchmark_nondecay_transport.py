"""Isolated eager CUDA costs and streaming equivalence, not a language score.

Run only when other GPU experiments have finished. The state bound is per
generated byte at fixed width; training still stores O(T) activations.
"""
import argparse
from dataclasses import asdict
import gc
import json
from pathlib import Path
import statistics
import time

import torch

from drrem.core.causal_transport import CausalTransportConfig,CausalTransportMachine,response_objective
from drrem.core.causal_decode import CausalTransportDecoder
from drrem.core.nondecay_transport import MemoryConfig,NondecayTransportMachine
from drrem.core.nondecay_decode import NondecayTransportDecoder
from drrem.core.transport_checkpoint import model_from_protocol


def timed(call,repeats):
    values=[]
    for _ in range(repeats):
        torch.cuda.synchronize();start=time.perf_counter();call();torch.cuda.synchronize()
        values.append(time.perf_counter()-start)
    return {'median_seconds':statistics.median(values),'seconds':values}


def memory_bytes(decoder):
    if isinstance(decoder,NondecayTransportDecoder):return decoder.state_bytes()
    return decoder.valid.numel()*decoder.valid.element_size()+sum(
        t.numel()*t.element_size() for pair in decoder.buffers.values() for t in pair)


def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--out',type=Path,required=True)
    p.add_argument('--lengths',nargs='+',type=int,default=[256,768,2048,4096])
    p.add_argument('--arms',nargs='+',default=['attention','byte_bank','phase_sum','phase_delta'])
    p.add_argument('--repeat',type=int,default=3)
    p.add_argument('--decode',type=int,default=16)
    p.add_argument('--trained-bank',type=Path)
    a=p.parse_args();torch.set_num_threads(2)
    if a.out.exists():raise FileExistsError(a.out)
    cfg=CausalTransportConfig(neurons=1024,layers=3,hops=6,heads=8,checkpoint_hops=False)
    records={'scope':'isolated eager CUDA synthetic costs; fresh models; no LM quality claims',
             'device':torch.cuda.get_device_name(),'torch':torch.__version__,'config':asdict(cfg),
             'precision':'BF16 autocast; phase state algebra FP32','arms':{}}
    def save():
        a.out.parent.mkdir(parents=True,exist_ok=True);a.out.write_text(json.dumps(records,indent=2)+'\n')
    for arm in a.arms:
        torch.manual_seed(1288)
        m=(CausalTransportMachine(cfg) if arm=='attention' else NondecayTransportMachine(cfg,MemoryConfig(arm,64))).cuda()
        rows={};records['arms'][arm]=rows
        seq=torch.randint(256,(8,769),device='cuda');valid=torch.ones_like(seq[:,:-1],dtype=torch.bool)
        response=valid.clone();response[:,:512]=False
        opt=torch.optim.Adam(m.parameters(),lr=3e-4,betas=(.9,.95))
        def train_step():
            m.train();opt.zero_grad(set_to_none=True)
            with torch.autocast('cuda',dtype=torch.bfloat16):
                loss,_,_=response_objective(m(seq[:,:-1],valid),seq,response,valid)
            loss.backward();torch.nn.utils.clip_grad_norm_(m.parameters(),1.,error_if_nonfinite=True);opt.step()
        train_step();train_step();torch.cuda.reset_peak_memory_stats()
        rows['adam_b8_t768']=timed(train_step,a.repeat)
        rows['adam_b8_t768']['peak_allocated_gib']=torch.cuda.max_memory_allocated()/2**30
        del opt,seq,valid,response,train_step
        m.zero_grad(set_to_none=True);m.eval();gc.collect();torch.cuda.empty_cache()
        for length in a.lengths:
            ids=torch.randint(256,(1,length+a.decode),device='cuda')
            @torch.no_grad()
            def forward():
                with torch.autocast('cuda',dtype=torch.bfloat16):return m(ids[:,:length])
            forward();torch.cuda.reset_peak_memory_stats();row={'parallel_prefix':timed(forward,a.repeat)}
            row['parallel_prefix']['peak_allocated_gib']=torch.cuda.max_memory_allocated()/2**30
            decoder=(CausalTransportDecoder(m,capacity=length+a.decode,precision='bf16') if arm=='attention'
                     else NondecayTransportDecoder(m,precision='bf16'))
            torch.cuda.synchronize();start=time.perf_counter();decoder.prefill(ids[:,:length]);torch.cuda.synchronize()
            row['prefill_with_state_seconds']=time.perf_counter()-start
            row['persistent_bytes_after_prefill']=memory_bytes(decoder)
            actual=[];times=[]
            for t in range(length,length+a.decode):
                torch.cuda.synchronize();start=time.perf_counter();actual.append(decoder.step(ids[:,t]));torch.cuda.synchronize()
                times.append(time.perf_counter()-start)
            row['decode_median_seconds']=statistics.median(times[2:]);row['decode_seconds']=times
            row['persistent_bytes_after_decode']=memory_bytes(decoder)
            with torch.no_grad(),torch.autocast('cuda',dtype=torch.bfloat16):expected=m(ids)[:,length:]
            actual=torch.cat(actual,1).float();expected=expected.float()
            row['stream_vs_parallel']={'max_logit_absolute':float((actual-expected).abs().max()),
                'rms_logit_difference':float((actual-expected).square().mean().sqrt()),
                'mean_KL_nats':float((expected.softmax(-1)*(expected.log_softmax(-1)-actual.log_softmax(-1))).sum(-1).mean())}
            rows[str(length)]=row;save();print(json.dumps({'arm':arm,'length':length,**row}),flush=True)
            del decoder,actual,expected,ids,forward
            gc.collect();torch.cuda.empty_cache()
        del m;gc.collect();torch.cuda.empty_cache()
    if a.trained_bank:
        protocol=json.loads((a.trained_bank/'protocol.json').read_text())
        ck=torch.load(a.trained_bank/'best_weights.pt',map_location='cpu',weights_only=False)
        m=model_from_protocol(protocol).cuda().eval();m.load_state_dict(ck['model']);torch.manual_seed(731)
        ids=torch.randint(256,(1,784),device='cuda');checks={}
        for precision in ['fp32','bf16']:
            decoder=NondecayTransportDecoder(m,precision=precision);decoder.prefill(ids[:,:768])
            with torch.no_grad(),torch.autocast('cuda',dtype=torch.bfloat16,enabled=precision=='bf16'):expected=m(ids)[:,768:].float()
            actual=torch.cat([decoder.step(ids[:,t]) for t in range(768,784)],1).float()
            checks[precision]={'max_logit_absolute':float((actual-expected).abs().max()),
                'rms_logit_difference':float((actual-expected).square().mean().sqrt()),
                'mean_KL_nats':float((expected.softmax(-1)*(expected.log_softmax(-1)-actual.log_softmax(-1))).sum(-1).mean()),
                'state_bytes':decoder.state_bytes()}
        records['trained_bank']={'run':str(a.trained_bank),'step':ck['step'],'random_byte_prefix_parity':checks};save()
    save()


if __name__=='__main__':main()
